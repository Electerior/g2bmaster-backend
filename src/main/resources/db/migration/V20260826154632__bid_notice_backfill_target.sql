-- V20260826154632__bid_notice_backfill_target.sql
-- 적재 상태 행에 '이 줄기는 어디까지만 훑는다'는 상한(target_to)을 붙인다.
--
-- 왜 필요한가:
--   5년치 과거 공고를 채우려면 [5년 전 → 지금] 을 훑어야 하는데, 그것을 기존
--   워터마크로 하려면 워터마크를 5년 전으로 되돌려야 한다. 그러면 되감은 순간부터
--   따라잡을 때까지(실측 추정 3~6시간) **오늘 올라온 공고가 색인되지 않는다** —
--   적재기는 5년 전 구간을 훑느라 머리 쪽을 보지 못한다.
--
--   그래서 과거 구간을 **별도 줄기**로 돌린다. 출처 하나가 상태 행 둘을 갖는다:
--     bid-announce:물품            워터마크 = 머리(지금). 평시 증분이 계속 전진한다
--     backfill:bid-announce:물품   워터마크 = 과거 커서. 5년 전에서 시작해 전진한다
--   둘 다 같은 upsert 로 bid_notice 에 쓰므로 겹쳐도 안전하고(차수 가드가 있다),
--   과거 줄기가 몇 시간을 돌든 신선도는 그대로다.
--
--   과거 줄기에는 끝이 있어야 한다. 그 끝이 target_to 다 — 백필을 지시한 시각이며,
--   워터마크가 여기에 닿으면 그 출처의 백필은 끝난 것이다(머리 줄기가 이미 그
--   시각부터를 맡고 있다). 평시 줄기는 끝이 없으므로 NULL 이고, 그때 상한은 '지금'이다.
--
--   회차 상한(MAX_ROWS_PER_RUN)에 걸리면 워터마크가 실제로 훑은 끝까지만 전진하는
--   기존 규칙을 그대로 쓴다. 즉 이 컬럼 하나로 "재개 가능한 백필"이 성립한다 —
--   앱이 죽어도 진행 상황은 DB 에 남는다.
--
-- 주의:
--   - 머지된 뒤에는 이 파일을 고치지 않는다. Flyway 가 체크섬을 들고 있어서,
--     이미 적용한 사람의 앱이 기동하지 않는다. 정정은 새 파일로 한다.
--   - ENUM 은 말미 append 만 한다(INSTANT). 재배열·삭제는 ALGORITHM=COPY 다.
-- ============================================================

ALTER TABLE `bid_notice_sync_state`
  ADD COLUMN `target_to` DATETIME(6) NULL
    COMMENT '이 줄기가 훑을 상한(등록일시). NULL 이면 상한 없음(=지금) — 평시 줄기가 그렇다. backfill:* 줄기는 백필을 지시한 시각이고, watermark 가 여기에 닿으면 완료다'
    AFTER `watermark`;
