-- ============================================================
-- V20260814132535__bid_notice_margin_rate.sql
-- 공고 검색 목록을 **마진율로 정렬**할 수 있게 마진 축을 색인에 물질화한다.
--
-- 왜 필요한가:
--   마진율은 (공고 예산 − 우리 원가) 로만 나오는 값인데, 원가는 bid_notice 에 없다.
--   지금까지 원가가 사는 곳은 둘뿐이다:
--     1) saved_notice.price_total   — 사람이 가격표에서 확정한 합계
--     2) deal_analysis_result.result_json → $.deal.cost  — deep 분석이 추정한 원가
--   두 곳 모두 검색 질의에 조인할 수 없다. (1)은 저장 공고에만 있고, (2)는 입력 해시마다
--   행이 하나씩이라 공고 하나에 여러 행이며 값이 JSON 안에 있다. ORDER BY 를 그 위에 얹으면
--   51,478행 전수 스캔 + JSON 추출 + filesort 가 매 검색마다 돈다.
--
--   그래서 filter_amount(V20260814113541) 와 **같은 처방**을 쓴다: 정렬이 보는 값을 컬럼으로
--   내려놓고 인덱스를 건다. 다른 점은 원가가 파생이 아니라 **바깥에서 들어오는 사실**이라는
--   것이라, 원가만 실제 컬럼으로 받고 비율은 생성 컬럼으로 계산한다 — 비율 정의가 코드와
--   DB 두 곳에 생기면 반드시 갈라진다.
--
-- 마진율 정의 (부가세 처리가 핵심이다):
--   margin_rate = (실추정가 − 원가) / 실추정가 × 100,   실추정가 = filter_amount × 1.1
--
--   두 전제가 있고 둘 다 이 저장소의 기존 규약이다:
--     · filter_amount 는 **부가세 별도**다. 추정가격(estimatedPrice)이 그렇다.
--     · margin_cost 는 **부가세 포함**이다. 원가의 출처인 다나와·아이티마야 판매가가 그렇고,
--       saved_notice 의 가격표도 그 값을 그대로 담는다.
--   saved_notice.real_estimate 주석이 이미 같은 규약을 적어 두었다("실추정가 = 추정가 × 1.1.
--   견적 합계와 견줄 값"). 공급가 기준으로 적어도 같은 수다 — (A − C/1.1)/A ≡ (1.1A − C)/1.1A.
--
--   ⚠ 대표 금액이 **배정예산**인 행(사전규격 12,120건 · NURI 1,171건)은 예산이 이미 부가세를
--     품고 있을 수 있어 이 환산이 마진을 10% 낙관적으로 만든다. 그래도 정렬 축을 금액 종류마다
--     가르지 않는다 — 종류는 응답의 amountKind 로 이미 내려가고, 축이 둘이면 "무엇으로 정렬된
--     목록인지"를 아무도 설명하지 못하게 된다. 이 한계는 응답의 marginBasis 로 알린다.
--
-- 왜 원가를 BIGINT 실 컬럼으로 받는가 (JSON 에서 뽑지 않고):
--   deal_analysis_result 는 (입력 해시 → 결과) 캐시라 공고당 행이 여럿이고, 어느 것이 '지금
--   맞는 원가'인지 SQL 로 고를 수 없다. 사람이 확정한 값(confirmed)이 추정(estimated)을 이겨야
--   한다는 규칙도 SQL 조인으로는 표현되지 않는다. 그 판정은 쓰기 시점에 한 번만 하고
--   (BidNoticeIndexRepository.updateMargin), 검색은 결과만 읽는다.
--
-- 클램프(±99999.99)를 두는 이유:
--   원가가 예산보다 훨씬 클 수 있다(예산 100만 원짜리 공고에 GPU 서버 원가 10억이 붙는 오탐).
--   그대로 두면 -90,900% 가 나와 DECIMAL 범위를 넘고, 생성 컬럼 평가 오류는 **INSERT 자체를
--   실패시킨다** — 적재기가 죽는다. 포화시키면 정렬 순서는 그대로고(맨 뒤) 값만 뭉갠다.
--
-- 주의:
--   - 머지된 뒤에는 이 파일을 고치지 않는다. Flyway 가 체크섬을 들고 있어서,
--     이미 적용한 사람의 앱이 기동하지 않는다. 정정은 새 파일로 한다.
--   - ENUM 은 말미 append 만 한다(INSTANT). 재배열·삭제는 ALGORITHM=COPY 다.
-- ============================================================

-- ─────────────────────────────────────────────────────────────
-- 1) 원가와 그 출처.
--
-- margin_source 가 단순한 메모가 아니라 **쓰기 우선순위**다. 사람이 확정한 원가는 추정이
-- 덮지 못한다(updateMargin 의 WHERE 절). 그 규칙이 없으면 야간 일괄 분석이 영업이 손으로
-- 맞춰 둔 가격표를 조용히 밀어낸다.
--
-- 적재기(upsertAll)는 이 세 칸을 갱신 목록에 넣지 않는다 — ai_summary 와 같은 이유로,
-- 재적재가 다른 파이프라인이 채운 값을 지워서는 안 된다.
-- ─────────────────────────────────────────────────────────────
ALTER TABLE `bid_notice`
  ADD COLUMN `margin_cost` BIGINT DEFAULT NULL
    COMMENT '원가(원, 부가세 포함) — 확정 가격표 합계 또는 deep 분석 추정 원가',
  ADD COLUMN `margin_source` ENUM('confirmed','estimated') DEFAULT NULL
    COMMENT '원가 출처 — confirmed(사람이 확정)가 estimated(AI 추정)를 이긴다',
  ADD COLUMN `margin_updated_at` DATETIME(6) DEFAULT NULL
    COMMENT '원가를 마지막으로 반영한 시각(KST)';

-- ─────────────────────────────────────────────────────────────
-- 2) 마진율 — 생성 컬럼.
--
-- VIRTUAL 인 이유는 filter_amount(V20260814113541)·estimated_price(V11) 와 같다: ALTER 가
-- 메타데이터 변경으로 끝나고, 값은 인덱스에만 실체화된다. filter_amount 를 참조하는 생성
-- 컬럼이라는 점만 다른데, MySQL 은 **앞서 정의된** 생성 컬럼 참조를 허용한다(filter_amount 는
-- 이 파일보다 먼저 붙었다).
--
-- 덤: 재적재로 price_detail 이 바뀌면 filter_amount 가 따라 바뀌고 마진율도 자동으로 맞는다.
-- 비율까지 실 컬럼으로 저장했다면 예산이 정정된 공고가 옛 마진율을 그대로 달고 있게 된다.
-- ─────────────────────────────────────────────────────────────
ALTER TABLE `bid_notice`
  ADD COLUMN `margin_rate` DECIMAL(7,2)
    GENERATED ALWAYS AS (
      LEAST(99999.99, GREATEST(-99999.99,
        ROUND(
          (`filter_amount` * 1.1 - `margin_cost`) / NULLIF(`filter_amount` * 1.1, 0) * 100,
          2)
      ))
    ) VIRTUAL
    COMMENT '마진율(%) — (실추정가 − 원가)/실추정가. 실추정가 = 대표금액 × 1.1. 정렬·필터 전용';

-- ─────────────────────────────────────────────────────────────
-- 3) 인덱스. 둘 다 DESC 선언이며 근거는 filter_amount 와 같다 — InnoDB 보조 인덱스는 키가
-- 같은 구간 안에서 PK 를 오름차순으로 담으므로 `margin_rate DESC, id ASC` 정렬이 저장 순서와
-- 맞아떨어져 정렬이 공짜가 된다. 화면 기본이 '마진 높은 순'이라 그쪽을 정방향으로 둔다.
--
-- NULL(원가를 아직 모르는 공고 — 지금은 절대다수다)은 MySQL 에서 가장 작은 값이라 DESC 스캔의
-- 맨 뒤로 밀린다. 즉 마진순 정렬은 분석된 공고부터 보여 주고 미분석 공고가 뒤를 채운다.
-- 결과 집합을 줄이지 않는 것이 중요하다 — '마진순으로 봤더니 공고가 사라졌다'가 되면 안 된다.
--
-- ⚠ 이 방향 선언은 BidNoticeSearchService.INDEX_DIRECTION 표와 짝이다. 한쪽만 바꾸면
--   같은 인덱스를 쓰고도 수천 행을 다시 정렬한다(BidNoticeSortTiebreakerTest 가 지킨다).
-- ─────────────────────────────────────────────────────────────

-- 탭(category) 안에서 마진순. 화면의 기본 사용 패턴이 '탭을 고른 뒤 좁히기'다.
ALTER TABLE `bid_notice`
  ADD KEY `ix_bid_notice_category_margin_rate` (`category`, `margin_rate` DESC);

-- 탭을 고르지 않은 '전체'에서 마진순 전용. 이것이 없으면 전체 스캔 + filesort 이고,
-- 있으면 LIMIT 만큼만 읽고 멈춘다.
ALTER TABLE `bid_notice`
  ADD KEY `ix_bid_notice_margin_rate` (`margin_rate` DESC);
